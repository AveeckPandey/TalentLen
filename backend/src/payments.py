"""Razorpay payment gateway integration for order creation and webhook/signature verification."""

import logging
import time
from typing import Dict, Any, Optional
import razorpay
from fastapi import HTTPException

from src.config import settings
from src.models import PlanTier, TIER_CONFIGS
from src.quota import quota_manager

logger = logging.getLogger(__name__)

# INR pricing in paise (1 INR = 100 paise)
TIER_PRICES_INR = {
    PlanTier.FREE: 0,
    PlanTier.PRO_29: 249900,      # ₹2,499 (~$29)
    PlanTier.ENTERPRISE: 849900,  # ₹8,499 (~$99)
}

# USD pricing in cents (1 USD = 100 cents)
TIER_PRICES_USD = {
    PlanTier.FREE: 0,
    PlanTier.PRO_29: 2900,        # $29
    PlanTier.ENTERPRISE: 9900,    # $99
}


def get_razorpay_client() -> razorpay.Client:
    """Initialize and return Razorpay client using configured test/live keys."""
    if not settings.RAZORPAY_KEY_ID or not settings.RAZORPAY_KEY_SECRET:
        raise HTTPException(
            status_code=500,
            detail="Razorpay credentials not configured. Please set RAZORPAY_KEY_ID and RAZORPAY_KEY_SECRET in .env",
        )
    return razorpay.Client(auth=(settings.RAZORPAY_KEY_ID, settings.RAZORPAY_KEY_SECRET))


def create_order(
    user_id: str,
    tier: PlanTier = PlanTier.PRO_29,
    currency: str = "INR",
) -> Dict[str, Any]:
    """
    Create a new Razorpay checkout order for a specific plan tier.
    Records order in database before returning to caller.
    """
    client = get_razorpay_client()
    curr_upper = currency.upper().strip()

    if curr_upper == "USD":
        amount = TIER_PRICES_USD.get(tier, 2900)
    else:
        curr_upper = "INR"
        amount = TIER_PRICES_INR.get(tier, 249900)

    tier_cfg = TIER_CONFIGS.get(tier, TIER_CONFIGS[PlanTier.PRO_29])
    receipt_id = f"rcpt_{user_id[:8]}_{int(time.time())}"

    order_payload = {
        "amount": amount,
        "currency": curr_upper,
        "receipt": receipt_id,
        "notes": {
            "user_id": user_id,
            "tier": tier.value,
            "tier_name": tier_cfg.display_name,
        },
    }

    try:
        order = client.order.create(data=order_payload)
        order_id = order["id"]
        logger.info(f"Created Razorpay order {order_id} for user {user_id} (tier={tier.value})")

        # Record in local persistence
        quota_manager.record_payment_order(
            order_id=order_id,
            user_id=user_id,
            tier=tier,
            amount=amount,
            currency=curr_upper,
        )

        return {
            "order_id": order_id,
            "amount": amount,
            "currency": curr_upper,
            "key_id": settings.RAZORPAY_KEY_ID,
            "tier": tier,
            "tier_name": tier_cfg.display_name,
        }
    except Exception as e:
        logger.error(f"Failed to create Razorpay order: {e}")
        raise HTTPException(status_code=502, detail=f"Razorpay order creation failed: {e}")


def verify_payment_signature(
    razorpay_order_id: str,
    razorpay_payment_id: str,
    razorpay_signature: str,
) -> bool:
    """
    Verify payment signature generated by Razorpay using HMAC SHA256.
    Returns True if authentic, False otherwise.
    """
    client = get_razorpay_client()
    params_dict = {
        "razorpay_order_id": razorpay_order_id,
        "razorpay_payment_id": razorpay_payment_id,
        "razorpay_signature": razorpay_signature,
    }

    try:
        client.utility.verify_payment_signature(params_dict)
        return True
    except razorpay.errors.SignatureVerificationError:
        logger.warning(
            f"Signature verification failed for order {razorpay_order_id}, payment {razorpay_payment_id}"
        )
        return False
    except Exception as e:
        logger.error(f"Unexpected error verifying Razorpay signature: {e}")
        return False
